#Requires -Version 5.1
<#
.SYNOPSIS
  Build DedSecCCTV-Setup-<version>.exe with Inno Setup 6.

.DESCRIPTION
  - Reads APP_VERSION from ..\app.py (or -AppVersion).
  - Writes version.inc for the .iss script.
  - Locates ISCC.exe (common install paths, PATH, or registry).
  - Compiles DedSecCCTV.iss -> installer\Output\

.PARAMETER AppVersion
  Override version (e.g. 1.0.3). Default: parse from app.py.

.PARAMETER DistDir
  Folder containing DedSecCCTV.exe (Nuitka output). Default: ..\DedSecCCTV

.PARAMETER SkipWingetHint
  Do not print winget install instructions when ISCC is missing.
#>
[CmdletBinding()]
param(
    [string]$AppVersion,
    [string]$DistDir,
    [switch]$SkipWingetHint
)

$ErrorActionPreference = 'Stop'
$InstallerDir = $PSScriptRoot
$SourceRoot   = Resolve-Path (Join-Path $InstallerDir '..')
$IssPath      = Join-Path $InstallerDir 'DedSecCCTV.iss'
$VersionInc   = Join-Path $InstallerDir 'version.inc'
$AppPy        = Join-Path $SourceRoot 'app.py'

if (-not $DistDir) {
    $DistDir = Join-Path $SourceRoot 'DedSecCCTV'
}

function Get-AppVersionFromPy {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) {
        throw "app.py not found at $Path - pass -AppVersion explicitly."
    }
    $text = Get-Content -LiteralPath $Path -Raw -Encoding UTF8
    if ($text -match 'APP_VERSION\s*=\s*["'']([^"'']+)["'']') {
        return $Matches[1]
    }
    throw "Could not find APP_VERSION = `"...`" in $Path"
}

function Find-ISCC {
    $candidates = @(
        "${env:LocalAppData}\Programs\Inno Setup 6\ISCC.exe",
        "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
        "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
        "${env:LocalAppData}\Programs\Inno Setup 7\ISCC.exe",
        "${env:ProgramFiles(x86)}\Inno Setup 7\ISCC.exe",
        "$env:ProgramFiles\Inno Setup 7\ISCC.exe"
    )
    foreach ($c in $candidates) {
        if ($c -and (Test-Path -LiteralPath $c)) { return $c }
    }
    $cmd = Get-Command ISCC.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }

    # Uninstall registry (Inno Setup 6)
    foreach ($root in @('HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*',
                        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*',
                        'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*')) {
        try {
            $hit = Get-ItemProperty $root -ErrorAction SilentlyContinue |
                Where-Object { $_.DisplayName -match 'Inno Setup' -and $_.InstallLocation } |
                Select-Object -First 1
            if ($hit) {
                $p = Join-Path $hit.InstallLocation 'ISCC.exe'
                if (Test-Path -LiteralPath $p) { return $p }
            }
        } catch {}
    }
    return $null
}

if (-not $AppVersion) {
    $AppVersion = Get-AppVersionFromPy -Path $AppPy
}
if ($AppVersion -notmatch '^\d+(\.\d+){1,3}$') {
    throw "Invalid AppVersion '$AppVersion' (expected like 1.0.2)."
}

$exe = Join-Path $DistDir 'DedSecCCTV.exe'
if (-not (Test-Path -LiteralPath $exe)) {
    throw @"
Missing $exe

Build the app first from the source folder:
  python build.py

Optional (recommended for auto-update):
  python -m nuitka --onefile --windows-console-mode=disable --output-filename=DedSecUpdater.exe updater.py
  copy DedSecUpdater.exe DedSecCCTV\
"@
}

$updater = Join-Path $DistDir 'DedSecUpdater.exe'
if (-not (Test-Path -LiteralPath $updater)) {
    Write-Warning "DedSecUpdater.exe not found in $DistDir - auto-update will not work until it is shipped next to DedSecCCTV.exe."
}

# version.inc - used when ISCC is invoked without /DAppVersion
@(
    '; Auto-generated by build_installer.ps1 - do not edit by hand.'
    '#ifndef AppVersion'
    "  #define AppVersion `"$AppVersion`""
    '#endif'
) | Set-Content -LiteralPath $VersionInc -Encoding ASCII

$iscc = Find-ISCC
if (-not $iscc) {
    Write-Host ""
    Write-Host "Inno Setup compiler (ISCC.exe) was not found." -ForegroundColor Yellow
    if (-not $SkipWingetHint) {
        Write-Host @"

Install Inno Setup 6, then re-run this script:

  winget install --id JRSoftware.InnoSetup -e

Or download from https://jrsoftware.org/isinfo.php
"@
    }
    exit 1
}

Write-Host "ISCC:      $iscc"
Write-Host "Version:   $AppVersion"
Write-Host "Dist:      $DistDir"
Write-Host "Script:    $IssPath"

$outDir = Join-Path $InstallerDir 'Output'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

& $iscc /DAppVersion=$AppVersion $IssPath
if ($LASTEXITCODE -ne 0) {
    throw "ISCC failed with exit code $LASTEXITCODE"
}

$setup = Join-Path $outDir "DedSecCCTV-Setup-$AppVersion.exe"
if (-not (Test-Path -LiteralPath $setup)) {
    throw "Expected output missing: $setup"
}

Write-Host ""
Write-Host "OK  $setup" -ForegroundColor Green
Write-Host "Size: $([math]::Round((Get-Item $setup).Length / 1MB, 1)) MB"
